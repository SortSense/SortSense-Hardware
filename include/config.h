/**
 * @file config.h
 * @brief Hardware pinout, camera parameters, and peripheral reservations for
 * SortSense.
 * @target ESP32-S3 WROOM CAM (ESP32-S3-WROOM-1-N16R8) with OV5640 Image Sensor.
 *
 * This configuration file defines all pin assignments, communication bus
 * frequencies, calibration thresholds, and system constants for the SortSense
 * smart waste sorter. Every constant enforces strict fixed-width integer types
 * (int8_t, uint8_t, uint16_t, uint32_t, size_t) to guarantee cross-platform
 * predictability and prevent implicit conversion bugs.
 *
 * All 25 active GPIO assignments have been mathematically verified to
 * completely isolate internal Octal PSRAM lines (GPIO 33..37), internal SPI
 * Flash lines (GPIO 26..32), native USB CDC pins (GPIO 19, 20), UART0 console
 * pins (GPIO 43, 44), and hardware strapping pins.
 *
 * For each configurable setting below, documentation covers:
 * - Available choices and valid ranges
 * - How to adjust the setting
 * - Why and when you would change it based on hardware and environment
 */

